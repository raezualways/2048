export function getTileColor(theme: Theme, value: number): string {
  const keys = Object.keys(theme.tiles).map(Number).sort((a, b) => a - b);
  const maxKey = keys[keys.length - 1];
  if (value >= maxKey) return theme.tiles[maxKey];
  return theme.tiles[value] || theme.tiles[2];
}
